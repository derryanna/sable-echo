const pluralRules = new Map();
function pluralCategory(language, count) {
  if (!pluralRules.has(language)) pluralRules.set(language, new Intl.PluralRules(language));
  return pluralRules.get(language).select(count);
}

function lookup(key, language, count) {
  const table = STRINGS[language];
  if (Number.isFinite(count)) {
    const plural = table[`${key}.${pluralCategory(language, count)}`] ?? table[`${key}.other`];
    if (plural !== undefined) return plural;
  }
  return table[key];
}

/** Localized string; unknown languages fall back to Russian, unknown keys return the key itself. */
export function t(key, language = DEFAULT_LANGUAGE, vars) {
  const lang = STRINGS[language] ? language : DEFAULT_LANGUAGE;
  const text = lookup(key, lang, vars?.count) ?? lookup(key, DEFAULT_LANGUAGE, vars?.count) ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match)) : text;
}

